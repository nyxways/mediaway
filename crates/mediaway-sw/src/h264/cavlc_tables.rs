//! CAVLC variable-length code tables (ITU-T H.264 Tables 9-5, 9-7, 9-8, 9-9, 9-10).
//!
//! Codewords are kept as bit-string literals (`"0"`/`"1"` characters) copied verbatim from
//! the spec tables rather than hand-converted to numeric `(code, length)` pairs — that
//! keeps the only "transcription step" a straight character-for-character copy, with the
//! bit-string -> `(u32, u8)` conversion done once by [`super::cavlc::parse_bits`] instead of
//! by hand. Data only; decode logic lives in [`super::cavlc`].
//!
//! `4:2:2`/`4:4:4`-only tables (`nC == -2`, the FLC-adjacent "for others" column of Table
//! 9-5) are out of scope — this crate decodes 4:2:0 only.
//!
//! **Provenance / verification (see `adr/0003-cavlc-i-slice-first-decode.md`):** these
//! codewords were transcribed from the spec via a permissively-licensed reference (an
//! MIT/BSD-style H.264 CAVLC encoder's literal `coeff_token`/`total_zeros`/`run_before`
//! table source, fetched and read for its numeric constants only — no code copied from
//! it), then spot-checked against independently-recalled known values (e.g. the FLC
//! formula for `nC >= 8`, and several `total_zeros`/`run_before` rows) before being typed
//! in here. [`ZIGZAG_4X4`] was cross-checked the same way.

